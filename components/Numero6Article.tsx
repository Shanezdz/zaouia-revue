function parseInline(text: string) {
  const parts = text.split(/(\[[^\]]+\]\(https?:\/\/[^)]+\)|\*\*[^*]+\*\*|\*[^*]+\*)/g);
  return parts.map((part, index) => {
    const link = part.match(/^\[([^\]]+)\]\((https?:\/\/[^)]+)\)$/);
    if (link) return <a key={index} href={link[2]} target="_blank" rel="noopener noreferrer">{link[1]} ↗</a>;
    if (part.startsWith("**") && part.endsWith("**")) return <strong key={index}>{part.slice(2, -2)}</strong>;
    if (part.startsWith("*") && part.endsWith("*")) return <em key={index}>{part.slice(1, -1)}</em>;
    return <React.Fragment key={index}>{part}</React.Fragment>;
  });
}

export default function Numero6Article() {
  const blocks = article.split(/\n\n+/);
  return (
    <article className="longform-article">
      {blocks.map((block, index) => {
        if (block.startsWith("### ")) return <h2 key={index}>{block.slice(4)}</h2>;
        const isQuestion = block.startsWith("**Que sommes-nous capables") || block.startsWith("**Que voulons-nous rendre") || block.startsWith("**À partir de quand");
        if (isQuestion) return <blockquote key={index}>{parseInline(block)}</blockquote>;
        return <p key={index}>{parseInline(block)}</p>;
      })}
    </article>
  );
}
